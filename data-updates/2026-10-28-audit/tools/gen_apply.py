#!/usr/bin/env python3
"""Writes apply.sql from this branch's frontend/data/tools.json (the hand-mirrored target state), so the
D1 values are byte-identical to what the site builds from. Run from the repo root:
  python3 data-updates/2026-10-28-audit/tools/gen_apply.py > data-updates/2026-10-28-audit/apply.sql"""
import json
tj = {t["domain"]: t for t in json.load(open("frontend/data/tools.json"))}
HELD = ["copy.ai", "jasper.ai", "replit.com", "runway.com", "stability.ai", "cursor.com", "windsurf.com", "midjourney.com", "otter.ai"]
UPD = ["github.com", "kimi.com", "mistral.ai", "zoom.com", "jetbrains.com", "grammarly.com", "heygen.com", "bolt.new", "openai.com"]
# Expected status before (D1 after 2026-10-28-recheck). github.com/otter.ai accept both, because it isn't
# recorded whether 2026-10-24-copilot-otter was ever run on D1 (the live site shows caveats from tools.json).
BEFORE = {"copy.ai": ["unrated"], "jasper.ai": ["unrated"], "replit.com": ["unrated"], "runway.com": ["unrated"],
          "stability.ai": ["unrated"], "midjourney.com": ["unrated", "compliant_with_caveats"],
          "cursor.com": ["compliant_with_caveats", "compliant"], "windsurf.com": ["compliant_with_caveats", "not_compliant"],
          "otter.ai": ["compliant_with_caveats", "not_compliant"], "github.com": ["compliant_with_caveats", "unrated"],
          **{d: [tj[d]["compliance_status"]] for d in UPD if d != "github.com"}}
# 4 Nov 2026 (Elliot): "Keep all 61 tools in PR #25, drop the audit's removals and re-check those 10".
# HELD is kept only for reference; this package no longer deletes them. They must still be in tools.json.
for d in HELD: assert d in tj, d
q = lambda s: "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"
b = lambda v: "NULL" if v is None else str(int(bool(v)))
ALL = sorted(UPD); IN = ", ".join(q(d) for d in ALL); HIN = ", ".join(q(d) for d in HELD)
P = print
P("""-- PolicyPeek 2026-10-28 full-catalog-audit data update. PREPARED ONLY, NOT RUN. Run AFTER 2026-10-28-recheck.
-- Needs Elliot's own approval before Jump runs it. Generated by tools/gen_apply.py from frontend/data/tools.json.
-- Source: deliverables/research/full-catalog-audit-2026-10-28.md, plus Jump's manual browser readings of 28 Oct
-- (ChatGPT, Midjourney, Otter). Atomic: D1 runs a --file as one batch; a failed GUARD/ASSERT (json() on invalid
-- text) rolls back every statement.
""")
P("-- 1. BEFORE SNAPSHOT (tools/gen_rollback.mjs rebuilds every row and the held tools' changelog rows from these)")
P(f"SELECT 'before_snapshot' AS snapshot, * FROM tools WHERE domain IN ({IN}) ORDER BY domain;")
P("SELECT 'before_counts' AS snapshot, compliance_status, COUNT(*) AS n FROM tools GROUP BY compliance_status ORDER BY compliance_status;")
P(f"SELECT 'queued_rechecks' AS snapshot, id, domain, status, created_at FROM pending_checks WHERE status IN ('pending','extracted') AND domain IN ({IN});\n")
P("-- 2. GUARDS")
for d in ALL:
    st = ", ".join(q(s) for s in BEFORE[d])
    P(f"SELECT CASE WHEN (SELECT COUNT(*) FROM tools WHERE domain = {q(d)} AND compliance_status IN ({st})) = 1 THEN 'ok: {d}' ELSE json('GUARD FAILED: {d} not in expected state') END AS guard;")
P("SELECT CASE WHEN (SELECT COUNT(*) FROM tools) = 61 THEN 'ok: 61 tools before' ELSE json('GUARD FAILED: expected 61 tools (run 2026-10-28-recheck first)') END AS guard_total;\n")
P("-- 3. HOLDS: none. The 9 tools the audit would have held (copy.ai, jasper.ai, replit.com, runway.com,")
P("--   stability.ai, cursor.com, windsurf.com, midjourney.com, otter.ai) stay published per Elliot, 4 Nov 2026.\n")
P("-- 4. UPDATES (manual entries, pinned with manual_override = 1 so the daily recheck can't auto-publish over them)")
for d in UPD:
    t = tj[d]
    P(f"UPDATE tools SET compliance_status = {q(t['compliance_status'])}, trains_on_user_data = {b(t['trains_on_user_data'])}, "
      f"summary = {q(t['summary'])}, source_urls = {q(json.dumps(t['source_urls'], ensure_ascii=False))}, auto_published = 0, manual_override = 1, "
      f"last_checked_at = {q(t['last_checked_at'])}, last_check_note = NULL, updated_at = strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE domain = {q(d)};")
P("UPDATE tools SET opt_out_available = 1 WHERE domain IN ('github.com', 'openai.com');\n")
P("-- 5. VERIFICATION")
P(f"SELECT 'after' AS v, domain, compliance_status, manual_override, auto_published, source_urls, summary FROM tools WHERE domain IN ({IN}) ORDER BY domain;")
P("SELECT 'after_counts' AS v, compliance_status, COUNT(*) AS n FROM tools GROUP BY compliance_status ORDER BY compliance_status;\n")
P("-- 6. ASSERTS")
P(f"SELECT CASE WHEN (SELECT COUNT(*) FROM tools WHERE domain IN ({HIN})) = 9 THEN 'ok: 9 kept' ELSE json('ASSERT FAILED: a previously-held tool is missing') END AS assert_kept;")
for d in UPD:
    t = tj[d]
    P(f"SELECT CASE WHEN (SELECT COUNT(*) FROM tools WHERE domain = {q(d)} AND compliance_status = {q(t['compliance_status'])} AND summary = {q(t['summary'])} AND source_urls = {q(json.dumps(t['source_urls'], ensure_ascii=False))} AND manual_override = 1) = 1 THEN 'ok: {d} updated' ELSE json('ASSERT FAILED: {d}') END AS assert_row;")
from collections import Counter
c = Counter(t["compliance_status"] for t in tj.values())
cond = "\n  AND ".join(f"(SELECT COUNT(*) FROM tools WHERE compliance_status = {q(k)}) = {c.get(k,0)}" for k in ["compliant_with_caveats","compliant","not_compliant","unrated","shared_domain_unverified","not_ai_tool"])
tot = "/".join(str(c.get(k,0)) for k in ["compliant_with_caveats","compliant","not_compliant","unrated","shared_domain_unverified","not_ai_tool"])
P(f"SELECT CASE WHEN {cond}\n  AND (SELECT COUNT(*) FROM tools) = {len(tj)}\n  THEN 'ok: totals {tot} ({len(tj)})' ELSE json('ASSERT FAILED: final totals wrong') END AS assert_totals;")
